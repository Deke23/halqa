"""Synthetic demo series for the two patient personas: HBPM week, ABPM day, wearable diary.

All values are generated by a seeded generator. Nobody real is described. The wearable diary holds
activity and sleep only: it never carries a blood pressure value (SPEC guardrail 5).
"""
from __future__ import annotations

import numpy as np

PERSONAS = {
    "patient_auh": {"name": "Khalid", "age": 34, "city": "Abu Dhabi", "screening_reading": "152/96",
                    "hbpm_mean": (147, 94), "abpm_day_mean": (142, 91), "abpm_dip": 0.10, "steps": (6200, 1600), "sleep": (6.2, 0.9)},
    "patient_yde": {"name": "Jean-Paul", "age": 47, "city": "Yaounde", "screening_reading": "164/102",
                    "hbpm_mean": (159, 99), "abpm_day_mean": (153, 96), "abpm_dip": 0.05, "steps": (5200, 1500), "sleep": (6.0, 0.8)},
}


def _avg(rows):
    return {"systolic": round(float(np.mean([r["systolic"] for r in rows])), 1),
            "diastolic": round(float(np.mean([r["diastolic"] for r in rows])), 1), "n": len(rows)}


def hbpm_week(rng, mean) -> dict:
    rows = []
    for day in range(1, 8):
        spread = 1.6 if day == 1 else 1.0  # first day is noisier and is discarded in the average
        shift = 6 if day == 1 else 0
        for session, times in (("morning", ("07:30", "07:32")), ("evening", ("20:00", "20:02"))):
            for k, tm in enumerate(times, 1):
                s = mean[0] + shift + (3 if session == "morning" else -3) + rng.normal(0, 5 * spread)
                d = mean[1] + shift * 0.6 + (2 if session == "morning" else -2) + rng.normal(0, 3.5 * spread)
                rows.append({"day": day, "session": session, "reading_no": k, "time": tm, "systolic": int(round(s)),
                             "diastolic": int(round(d)), "pulse": int(round(rng.normal(74, 6))), "source": "HOME_CUFF"})
    kept = [r for r in rows if r["day"] > 1]
    avg = _avg(kept)
    assert avg["systolic"] >= 140 and avg["diastolic"] >= 90, "demo HBPM average must be clearly raised"
    return {"readings": rows, "average_excluding_day_1": avg, "days_counted": 6,
            "note": "Two morning and two evening readings per day for 7 days. Day 1 is discarded from the average."}


def abpm_day(rng, day_mean, dip) -> dict:
    rows = []
    for hour in range(7, 23):
        for minute in (0, 30):
            rows.append({"time": f"{hour:02d}:{minute:02d}", "period": "day",
                         "systolic": int(round(day_mean[0] + rng.normal(0, 7))),
                         "diastolic": int(round(day_mean[1] + rng.normal(0, 5))), "pulse": int(round(rng.normal(76, 7)))})
    for hour in list(range(23, 24)) + list(range(0, 7)):
        rows.append({"time": f"{hour:02d}:00", "period": "night",
                     "systolic": int(round(day_mean[0] * (1 - dip) + rng.normal(0, 6))),
                     "diastolic": int(round(day_mean[1] * (1 - dip) + rng.normal(0, 4))), "pulse": int(round(rng.normal(62, 5)))})
    day = [r for r in rows if r["period"] == "day"]
    night = [r for r in rows if r["period"] == "night"]
    avg = _avg(day)
    assert avg["systolic"] >= 135 and avg["diastolic"] >= 85, "demo ABPM daytime average must be at or above 135/85"
    for r in rows:
        r["source"] = "ABPM"
    return {"readings": rows, "daytime_average": avg, "night_average": _avg(night),
            "note": "One 24-hour recording: every 30 minutes by day (07:00 to 22:59), hourly by night."}


def wearable_diary(rng, steps, sleep) -> dict:
    days = []
    for day in range(1, 15):
        st = int(max(1500, rng.normal(*steps)))
        days.append({"day": day, "steps": st, "active_minutes": int(max(5, st / 140 + rng.normal(0, 6))),
                     "sleep_hours": round(float(np.clip(rng.normal(*sleep), 4.0, 9.0)), 1),
                     "sleep_efficiency_pct": int(np.clip(rng.normal(86, 4), 70, 97))})
    return {"days": days, "note": "Activity and sleep diary only. It holds no blood pressure values and is never used as one."}


def build(seed: int) -> dict:
    out = {"synthetic": True, "disclaimer": "All values are synthetic and generated by seeded code. No record describes a real person.",
           "personas": {}}
    for i, (key, p) in enumerate(PERSONAS.items()):
        rng = np.random.default_rng([seed, 7, i])
        out["personas"][key] = {
            "name": p["name"], "age": p["age"], "city": p["city"], "screening_reading": p["screening_reading"],
            "hbpm_week": hbpm_week(rng, p["hbpm_mean"]),
            "abpm_day": abpm_day(rng, p["abpm_day_mean"], p["abpm_dip"]),
            "wearable_diary": wearable_diary(rng, p["steps"], p["sleep"]),
        }
    return out
